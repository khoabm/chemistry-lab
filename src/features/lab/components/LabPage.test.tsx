describe('M5 alcohol lamp interaction', () => {
  function place(name: string, x: number, y: number) {
    const source = screen.getByRole('button', { name: `Add ${name}` })
    pointer(source, 'down', 0, 0)
    pointer(source, 'move', 344 + x * 512, 163 + y * 274)
    pointer(source, 'up', 344 + x * 512, 163 + y * 274)
    fireEvent.click(source, { detail: 1 })
    return screen.getByRole('button', { name: `${name} 1` })
  }

  function litLamp() {
    const lamp = place('Alcohol lamp', 0.5, 0.7)
    fireEvent.click(screen.getByRole('button', { name: 'Ignite lamp' }), { detail: 0 })
    return lamp
  }

  it('starts off, explicitly ignites/extinguishes and preserves the existing bench hitbox/selection', () => {
    const lamp = place('Alcohol lamp', 0.5, 0.7)
    expect(screen.getByRole('status', { name: 'Lamp status' })).toHaveTextContent('Lamp extinguished.')
    expect(within(lamp).getByText('Off', { exact: true })).toBeVisible()
    expect(lamp.querySelector('.lamp-flame')).not.toBeInTheDocument()
    expect(bench().querySelector('.heating-zone')).not.toBeInTheDocument()
    fireEvent.click(lamp)
    expect(lamp.querySelector('.lamp-flame')).not.toBeInTheDocument()
    const position = lamp.getAttribute('style')
    const ignite = screen.getByRole('button', { name: 'Ignite lamp' })
    ignite.focus()
    fireEvent.click(ignite, { detail: 0 })
    expect(lamp.querySelector('.lamp-flame')).toBeInTheDocument()
    expect(lamp).toHaveAttribute('style', position)
    expect(lamp).toHaveAccessibleDescription(expect.stringContaining('Lamp lit.'))
    expect(within(lamp).queryByText('Lit', { exact: true })).not.toBeInTheDocument()
    expect(within(lamp).queryByText('Off', { exact: true })).not.toBeInTheDocument()
    expect(bench().querySelector('.heating-zone')).toBeInTheDocument()
    expect(within(bench()).queryByText('Heat zone', { exact: true })).not.toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Extinguish lamp' }))
    expect(lamp.querySelector('.lamp-flame')).not.toBeInTheDocument()
    expect(bench().querySelector('.heating-zone')).not.toBeInTheDocument()
    expect(lamp).toHaveAccessibleDescription(expect.stringContaining('Lamp extinguished.'))
    expect(within(lamp).getByText('Off', { exact: true })).toBeVisible()
  })

  it.each(['Beaker', 'Test tube'])('heats an empty/filled %s only in the zone, without running heat reactions', (name) => {
    const lamp = litLamp()
    const sample = place(name, 0.5, 0.48)
    expect(screen.getByRole('status', { name: 'Container heating' })).toHaveTextContent('Heating over a lit alcohol lamp.')
    expect(sample.querySelector('.container-heat-glow')).toBeInTheDocument()
    expect(sample).toHaveAccessibleDescription(expect.stringContaining('Heating over a lit alcohol lamp.'))
    expect(within(sample).getByText('Heating', { exact: true })).toBeVisible()
    expect(within(bench()).getAllByText('Heating', { exact: true })).toHaveLength(1)
    fireEvent.click(screen.getByRole('button', { name: 'Add Copper(II) carbonate' }))
    expect(sample.querySelector('[data-content-state="solid"]')).toHaveAttribute('fill', '#609d73')
    expect(sample.querySelector('[data-reaction-effect]')).not.toBeInTheDocument()
    expect(screen.queryByRole('status', { name: 'Mix result' })).not.toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Mix' }))
    expect(screen.getByRole('status', { name: 'Mix result' })).toHaveTextContent('No observable reaction.')
    fireEvent.click(screen.getByRole('tab', { name: 'Sample' }))
    fireEvent.keyDown(sample, { key: 'ArrowRight' })
    fireEvent.keyDown(sample, { key: 'ArrowRight' })
    expect(sample.querySelector('.container-heat-glow')).not.toBeInTheDocument()
    expect(screen.getByRole('status', { name: 'Container heating' })).toHaveTextContent('Not heating.')
    expect(within(sample).queryByText('Heating', { exact: true })).not.toBeInTheDocument()
    expect(sample).not.toHaveAccessibleDescription(expect.stringContaining('Heating over a lit alcohol lamp.'))
    fireEvent.keyDown(sample, { key: 'ArrowLeft' })
    expect(sample.querySelector('.container-heat-glow')).toBeInTheDocument()
    fireEvent.click(lamp)
    fireEvent.click(screen.getByRole('button', { name: 'Extinguish lamp' }))
    expect(sample.querySelector('.container-heat-glow')).not.toBeInTheDocument()
    expect(sample.querySelector('[data-content-state="solid"]')).toHaveAttribute('fill', '#609d73')
  })

  it('keeps committed heating during previews/cancellation/invalid drops, and stops it on a valid move away', () => {
    litLamp()
    const sample = place('Beaker', 0.5, 0.48)
    pointer(sample, 'down', 0, 0)
    pointer(sample, 'move', 400, 300)
    expect(document.querySelector('.equipment-drag-preview .container-heat-glow')).toBeInTheDocument()
    fireEvent.keyDown(sample, { key: 'Escape' })
    pointer(sample, 'up', 400, 300)
    expect(sample.querySelector('.container-heat-glow')).toBeInTheDocument()
    pointer(sample, 'down', 0, 0)
    pointer(sample, 'move', 100, 600)
    pointer(sample, 'up', 100, 600)
    expect(sample.querySelector('.container-heat-glow')).toBeInTheDocument()
    pointer(sample, 'down', 0, 0)
    pointer(sample, 'move', 400, 300)
    pointer(sample, 'up', 400, 300)
    expect(sample.querySelector('.container-heat-glow')).not.toBeInTheDocument()
  })

  it('preserves a lit lamp preview, disables its toggle while dragging and updates heating when moving the source', () => {
    const lamp = litLamp()
    const sample = place('Beaker', 0.5, 0.48)
    pointer(lamp, 'down', 0, 0)
    pointer(lamp, 'move', 400, 300)
    expect(document.querySelector('.equipment-drag-preview .lamp-flame')).toBeInTheDocument()
    const toggle = screen.getByRole('button', { name: 'Extinguish lamp' })
    expect(toggle).toBeDisabled()
    fireEvent.click(toggle)
    expect(lamp.querySelector('.lamp-flame')).toBeInTheDocument()
    expect(sample.querySelector('.container-heat-glow')).toBeInTheDocument()
    pointer(lamp, 'up', 400, 300)
    expect(sample.querySelector('.container-heat-glow')).not.toBeInTheDocument()
    expect(screen.getByRole('button', { name: 'Extinguish lamp' })).toBeEnabled()
  })

  it('isolates/reset multiple lamp instances', () => {
    const first = litLamp()
    expect(screen.queryByRole('status', { name: 'Container heating' })).not.toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Add Alcohol lamp' }))
    const second = screen.getByRole('button', { name: 'Alcohol lamp 2' })
    expect(second.querySelector('.lamp-flame')).not.toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Ignite lamp' }))
    fireEvent.click(first)
    fireEvent.click(screen.getByRole('button', { name: 'Extinguish lamp' }))
    expect(second.querySelector('.lamp-flame')).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Reset lab' }))
    expect(bench().querySelector('.lamp-flame')).not.toBeInTheDocument()
    expect(bench().querySelector('.heating-zone')).not.toBeInTheDocument()
    expect(screen.queryByRole('button', { name: 'Extinguish lamp' })).not.toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Add Alcohol lamp' }))
    expect(screen.getByRole('status', { name: 'Lamp status' })).toHaveTextContent('Lamp extinguished.')
  })

  it.each(['sample', 'lamp'])('ignores arrow movement during a %s drag so cancellation preserves heating', (kind) => {
    const lamp = litLamp()
    const sample = place('Beaker', 0.5, 0.48)
    const source = kind === 'sample' ? sample : lamp
    const position = source.getAttribute('style')
    pointer(source, 'down', 0, 0)
    pointer(source, 'move', 400, 300)
    fireEvent.keyDown(source, { key: 'ArrowRight', shiftKey: true })
    expect(source).toHaveAttribute('style', position)
    expect(sample.querySelector('.container-heat-glow')).toBeInTheDocument()
    fireEvent.keyDown(source, { key: 'Escape' })
    pointer(source, 'up', 400, 300)
    expect(source).toHaveAttribute('style', position)
    expect(sample.querySelector('.container-heat-glow')).toBeInTheDocument()
    fireEvent.keyDown(source, { key: 'ArrowRight', shiftKey: true })
    expect(source.getAttribute('style')).not.toBe(position)
    expect(sample.querySelector('.container-heat-glow')).not.toBeInTheDocument()
  })

  it('blocks keyboard equipment activation across controls while a pointer drag is active', () => {
    const lamp = litLamp()
    const sample = place('Beaker', 0.5, 0.48)
    const palette = screen.getByRole('button', { name: 'Add Alcohol lamp' })
    pointer(lamp, 'down', 0, 0)
    pointer(lamp, 'move', 400, 300)
    fireEvent.click(palette, { detail: 0 })
    fireEvent.click(sample, { detail: 0 })
    fireEvent.keyDown(sample, { key: 'ArrowRight', shiftKey: true })
    expect(items()).toHaveLength(2)
    expect(lamp).toHaveAttribute('aria-pressed', 'true')
    expect(sample.querySelector('.container-heat-glow')).toBeInTheDocument()
    fireEvent.keyDown(lamp, { key: 'Escape' })
    pointer(lamp, 'up', 400, 300)
    fireEvent.click(palette, { detail: 0 })
    expect(items()).toHaveLength(3)
  })
})

