import { mountSelectedSample } from '../../../../tests/mounting'
import { act, fireEvent, render, screen, within } from '@testing-library/react'
import { StrictMode } from 'react'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { LabPage } from './LabPage'
import * as engine from '../../../simulation/engine/evaluateReaction'
import * as dynamics from '../hooks/useReactionDynamics'
import { heatReactionDelayMs } from '../hooks/useHeatReactions'

class TestPointerEvent extends MouseEvent { readonly pointerId = 1 }
beforeEach(() => { vi.useFakeTimers(); vi.stubGlobal('PointerEvent', TestPointerEvent) })
afterEach(() => { vi.restoreAllMocks(); vi.unstubAllGlobals(); vi.useRealTimers() })
const click = (name: string) => fireEvent.click(screen.getByRole('button', { name }))
const choose = (label: string, id: string) => fireEvent.change(screen.getByRole('combobox', { name: label }), { target: { value: id } })
const tick = (time: number) => act(() => vi.advanceTimersByTime(time))

describe('M11 dropper workflow', () => {
  it('transfers the stable chemical once, preserves payload through locale/selection/movement, and requires explicit Mix', () => {
    const evaluate = vi.spyOn(engine, 'evaluateReaction')
    render(<StrictMode><LabPage /></StrictMode>)
    click('Add Beaker'); click('Add Hydrochloric acid'); click('Add Hydrochloric acid')
    click('Add Test tube'); click('Add Sodium hydroxide')
    click('Add Dropper')
    expect(screen.queryByRole('tablist')).not.toBeInTheDocument()
    expect(screen.getByRole('button', { name: 'Fill dropper' })).toBeDisabled()
    choose('Source container', 'equipment-1'); click('Fill dropper')
    expect(screen.getByRole('combobox', { name: 'Destination container' })).toHaveFocus()
    const dropper = screen.getByRole('button', { name: 'Dropper 1' })
    vi.spyOn(screen.getByRole('group', { name: 'Laboratory bench' }), 'getBoundingClientRect').mockReturnValue(new DOMRect(300, 100, 600, 400))
    expect(dropper).toHaveAccessibleDescription(expect.stringContaining('HCl'))
    expect(dropper.querySelector('.dropper-payload')).toHaveAttribute('data-chemical-id', 'hydrochloric-acid')
    const position = dropper.getAttribute('style')
    fireEvent.keyDown(dropper, { key: 'ArrowRight' })
    expect(dropper.getAttribute('style')).not.toBe(position)
    expect(dropper).toHaveAttribute('aria-pressed', 'true')
    click('Beaker 1')
    expect(screen.getByRole('list', { name: 'Container contents' })).toHaveTextContent('1 unit · Solution')
    click('Dropper 1')
    choose('Language', 'vi')
    expect(screen.getByRole('status', { name: 'Mẫu trong ống nhỏ giọt' })).toHaveTextContent('HCl · Hydrochloric acid')
    expect(screen.getByRole('status', { name: 'Mẫu trong ống nhỏ giọt' })).toHaveAttribute('aria-live', 'off')
    choose('Nhỏ vào', 'equipment-2'); click('Nhỏ mẫu')
    expect(screen.getByRole('status', { name: 'Mẫu trong ống nhỏ giọt' })).toHaveTextContent('Ống nhỏ giọt trống')
    expect(screen.getByRole('combobox', { name: 'Hút từ' })).toHaveFocus()
    expect(evaluate).not.toHaveBeenCalled()
    click('Ống nghiệm 1')
    expect(screen.getByRole('list', { name: 'Thành phần trong dụng cụ' })).toHaveTextContent('NaOH')
    expect(screen.getByRole('list', { name: 'Thành phần trong dụng cụ' })).toHaveTextContent('HCl')
    click('Trộn')
    // StrictMode invokes the pure reducer twice for this single explicit action.
    expect(evaluate).toHaveBeenCalledTimes(2)
    for (const [input] of evaluate.mock.calls) expect(input.trigger).toBe('mix')
    expect(screen.getByRole('status', { name: 'Kết quả trộn' })).toHaveTextContent('Simplified acid-base neutralization')
    click('Ống nhỏ giọt 1')
    click('Đặt lại phòng thí nghiệm')
    expect(screen.queryByRole('button', { name: 'Ống nhỏ giọt 1' })).not.toBeInTheDocument()
  })

  it('shows disabled source reasons and preserves independent payloads through direct drag, cancel and drop', () => {
    render(<LabPage />)
    click('Add Beaker'); click('Add Test tube'); click('Add Copper(II) carbonate')
    click('Add Dropper')
    expect(screen.getByRole('option', { name: /Beaker 1 — This source is empty/ })).toBeDisabled()
    expect(screen.getByRole('option', { name: /Test tube 1 — Solid samples/ })).toBeDisabled()
    click('Beaker 1'); click('Add Hydrochloric acid'); click('Add Hydrochloric acid')
    click('Dropper 1'); choose('Source container', 'equipment-1'); click('Fill dropper')
    click('Add Dropper')
    expect(screen.getByRole('status', { name: 'Dropper contents' })).toHaveTextContent('Dropper empty')
    choose('Source container', 'equipment-1'); click('Fill dropper')
    click('Dropper 1')
    expect(screen.getByRole('status', { name: 'Dropper contents' })).toHaveTextContent('Holding HCl')
    const bench = screen.getByRole('group', { name: 'Laboratory bench' })
    vi.spyOn(bench, 'getBoundingClientRect').mockReturnValue(new DOMRect(300, 100, 600, 400))
    const dropper = screen.getByRole('button', { name: 'Dropper 1' })
    const payload = dropper.querySelector('.dropper-payload')
    const visual = dropper.querySelector('.equipment-visual')
    fireEvent.pointerDown(dropper, { button: 0, clientX: 0, clientY: 0 })
    fireEvent.pointerMove(dropper, { clientX: 500, clientY: 300 })
    expect(document.querySelector('.equipment-drag-preview')).not.toBeInTheDocument()
    expect(dropper.querySelector('.dropper-payload')).toBe(payload)
    expect(payload).toHaveAttribute('data-chemical-id', 'hydrochloric-acid')
    expect(screen.getByRole('combobox', { name: 'Destination container' })).toBeDisabled()
    expect(screen.getByRole('button', { name: 'Dispense sample' })).toBeDisabled()
    fireEvent.keyDown(dropper, { key: 'Escape' })
    expect(document.querySelector('.equipment-drag-preview')).not.toBeInTheDocument()
    expect(dropper.querySelector('.dropper-payload')).toBeInTheDocument()
    fireEvent.pointerDown(dropper, { button: 0, clientX: 0, clientY: 0 })
    fireEvent.pointerMove(dropper, { clientX: 550, clientY: 330 })
    const draftPosition = dropper.getAttribute('style')
    fireEvent.pointerUp(dropper, { clientX: 550, clientY: 330 })
    expect(dropper).toHaveAttribute('style', draftPosition)
    expect(screen.getByRole('button', { name: 'Dropper 1' })).toBe(dropper)
    expect(dropper.querySelector('.equipment-visual')).toBe(visual)
    expect(dropper.querySelector('.dropper-payload')).toBe(payload)
    choose('Destination container', 'equipment-2'); click('Dispense sample')
    expect(screen.getByRole('button', { name: 'Dropper 2' }).querySelector('.dropper-payload')).toBeInTheDocument()
  })

  it('uses normal Heat generations after transfer and preserves an unrelated live reaction age/result', () => {
    const live = vi.spyOn(dynamics, 'useReactionDynamics')
    const evaluate = vi.spyOn(engine, 'evaluateReaction')
    render(<LabPage />)
    click('Add Beaker'); click('Add Hydrochloric acid'); click('Add Sodium bicarbonate'); click('Mix')
    const untouched = live.mock.calls.at(-1)![0][0]!
    const start = live.mock.results.at(-1)!.value.get(untouched.id).startedAt
    tick(2000)
    click('Add Alcohol lamp'); click('Ignite lamp')
    click('Add Test tube'); click('Add Hydrochloric acid'); click('Add Hydrochloric acid')
    mountSelectedSample('equipment-2')
    click('Add Dropper'); choose('Source container', 'equipment-3')
    tick(heatReactionDelayMs / 2)
    const calls = evaluate.mock.calls.length
    click('Fill dropper')
    expect(evaluate).toHaveBeenCalledTimes(calls)
    expect(live.mock.calls.at(-1)![0][0]).toBe(untouched)
    expect(live.mock.results.at(-1)!.value.get(untouched.id).startedAt).toBe(start)
    tick(heatReactionDelayMs / 2)
    expect(evaluate).toHaveBeenCalledTimes(calls)
    tick(heatReactionDelayMs / 2)
    expect(evaluate).toHaveBeenLastCalledWith({ contents: [{ chemicalId: 'hydrochloric-acid', quantity: 1 }], trigger: 'heat' })
    click('Test tube 1')
    expect(within(screen.getByRole('tabpanel', { name: 'Result' })).getByText('No observable reaction.')).toBeInTheDocument()
    tick(4000)
    expect(screen.getByRole('button', { name: 'Beaker 1' }).querySelector('[data-reaction-effect="gas"]')).not.toBeInTheDocument()
  })
})
